#!/usr/bin/env python3
"""Builds examples/blink.wasm + examples/blink_wasm.h - the same module guest/blink.c compiles to.
Exports: setup(), loop(), blink(pin, count). Imports: enable, disable, sleep, log."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "tests"))
from wasmgen import *

HELLO = b"eccles_wasm guest up\n"
LED = 2
m = Module()
enable = m.import_func("env", "enable", [I32], [I32])
disable = m.import_func("env", "disable", [I32], [I32])
sleep = m.import_func("env", "sleep", [I32], [I32])
log = m.import_func("env", "log", [I32, I32], [I32])
m.mem = (1, None)
m.data.append((16, HELLO))
m.func([], [], [], i32c(16) + i32c(len(HELLO)) + call(log) + DROP, export="setup")
m.func([], [], [], i32c(LED) + call(enable) + DROP + i32c(500) + call(sleep) + DROP +
                    i32c(LED) + call(disable) + DROP + i32c(500) + call(sleep) + DROP, export="loop")
m.func([I32, I32], [I32], [I32],                      # blink(pin, count) -> status of last disable
       block(EMPTY, loop(EMPTY, lget(1) + b"\x45" + br_if(1) + lget(0) + call(enable) + DROP + i32c(100) + call(sleep) + DROP +
                         lget(0) + call(disable) + lset(2) + i32c(100) + call(sleep) + DROP + lget(1) + i32c(1) + b"\x6b" + lset(1) + br(0))) + lget(2),
       export="blink")
data = m.build()
open(os.path.join(here, "blink.wasm"), "wb").write(data)
lines = ["/* generated by examples/make_blink_wasm.py (%d bytes) */" % len(data), "static const unsigned char blink_wasm[] = {"]
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
lines.append("};")
open(os.path.join(here, "blink_wasm.h"), "w").write("\n".join(lines) + "\n")
print("blink.wasm: %d bytes" % len(data))
