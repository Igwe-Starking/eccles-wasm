#!/usr/bin/env python3
"""wasm2c.py - turn a .wasm file into a C array you can compile into your firmware.

    python3 tools/wasm2c.py app.wasm app_wasm.h            # symbol name = app_wasm
    python3 tools/wasm2c.py app.wasm app_wasm.h my_module  # symbol name = my_module

The header defines:  const unsigned char <name>[]  and  const unsigned int <name>_len
On AVR-style chips with a separate flash address space add PROGMEM yourself; on ARM, ESP32, RP2040 `const` already puts it in flash.
"""
import os
import re
import sys


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    name = sys.argv[3] if len(sys.argv) > 3 else re.sub(r"\W", "_", os.path.splitext(os.path.basename(dst))[0])
    data = open(src, "rb").read()
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    with open(dst, "w") as f:
        f.write("/* generated by tools/wasm2c.py from %s - do not edit */\n" % os.path.basename(src))
        f.write("#pragma once\n")
        f.write("const unsigned char %s[] = {\n%s\n};\n" % (name, "\n".join(lines)))
        f.write("const unsigned int %s_len = %d;\n" % (name, len(data)))
    print("%s: %d bytes -> %s (%s, %s_len)" % (src, len(data), dst, name, name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
